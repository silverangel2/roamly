import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(new URL("..", import.meta.url).pathname);
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const domain = read("lib/roamly/customerDestinationChange.ts");
const migration = read("supabase/migrations/20260923_roamly_customer_destination_changes.sql");
const preview = read("app/api/trips/[id]/destination-change/route.ts");
const apply = read("app/api/trips/[id]/destination-change/[proposalId]/apply/route.ts");
const generation = read("lib/roamly/stagedItineraryGeneration.ts");
const ui = read("components/roamly/CustomerDestinationChange.tsx");

assert.match(domain, /normalizeDestinationSnapshot/);
assert.match(domain, /destinationSnapshotHash/);
assert.match(domain, /latitude.*longitude/s);
assert.match(domain, /destinationStops/);
assert.match(domain, /buildSuccessorDestinationIntent/);
assert.match(domain, /destinationSourceDatesEligible/);
assert.match(domain, /roamly_bookings/);
assert.match(domain, /superseded_by_booking_id/);
assert.match(domain, /booked.*paid.*reserved.*confirmed.*modified.*completed/s);
assert.match(domain, /recommended.*clicked.*cancelled.*refunded/s);
assert.doesNotMatch(domain, /trip_bookings/);
assert.match(migration, /create table public\.roamly_customer_trip_destination_changes/);
assert.match(migration, /requested_destination_snapshot jsonb not null/);
assert.match(migration, /expected_booking_snapshot jsonb/);
assert.match(migration, /expected_intent_snapshot jsonb/);
assert.match(migration, /for update/);
assert.match(migration, /roamly_bookings/);
assert.doesNotMatch(migration, /trip_bookings/);
assert.match(migration, /status = 'archived'/);
assert.match(migration, /status = 'applied'/);
assert.match(migration, /roamly_complete_customer_trip_destination_change/);
assert.match(migration, /roamly_fail_customer_trip_destination_change/);
assert.match(migration, /revoke all on function public\.roamly_reserve_customer_trip_destination_change/);
const reserveInsert = migration.match(/insert into public\.roamly_trips[\s\S]*?returning id into successor_id;/);
assert.ok(reserveInsert, "reserve successor INSERT must contain RETURNING id INTO successor_id");
assert.match(reserveInsert[0], /values[\s\S]*\)\s*returning id into successor_id;/);
assert.doesNotMatch(reserveInsert[0], /;\s*returning\s+id\s+into\s+successor_id/);
assert.match(preview, /normalizeDestinationSnapshot/);
assert.match(preview, /MULTI_CITY_DESTINATION_NOT_SUPPORTED/);
assert.match(preview, /destinationSourceDatesEligible/);
